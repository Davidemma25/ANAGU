CREATE TABLE IF NOT EXISTS geographic_reference_sources (
  id BIGSERIAL PRIMARY KEY,
  code VARCHAR(80) NOT NULL UNIQUE,
  title TEXT NOT NULL,
  source_url TEXT NOT NULL,
  license VARCHAR(120) NOT NULL,
  attribution TEXT NOT NULL,
  source_version VARCHAR(40) NOT NULL,
  reviewed_on DATE,
  retrieved_on DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE states
  ADD COLUMN IF NOT EXISTS source_code VARCHAR(20),
  ADD COLUMN IF NOT EXISTS center_lat DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS center_lng DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS source_id BIGINT REFERENCES geographic_reference_sources(id) ON DELETE RESTRICT;
ALTER TABLE local_government_areas
  ADD COLUMN IF NOT EXISTS source_code VARCHAR(20),
  ADD COLUMN IF NOT EXISTS center_lat DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS center_lng DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS source_id BIGINT REFERENCES geographic_reference_sources(id) ON DELETE RESTRICT;
ALTER TABLE communities
  ADD COLUMN IF NOT EXISTS source_code VARCHAR(30),
  ADD COLUMN IF NOT EXISTS center_lat DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS center_lng DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS place_type VARCHAR(20) NOT NULL DEFAULT 'COMMUNITY',
  ADD COLUMN IF NOT EXISTS source_id BIGINT REFERENCES geographic_reference_sources(id) ON DELETE RESTRICT;

CREATE UNIQUE INDEX IF NOT EXISTS idx_states_source_code
  ON states(source_code) WHERE source_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_lgas_source_code
  ON local_government_areas(source_code) WHERE source_code IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_communities_source_code
  ON communities(source_code) WHERE source_code IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_communities_lga_name
  ON communities(lga_id, name) WHERE is_active;

